export type IconName = keyof typeof ICONS;

/** Merge each row's lit pixels into horizontal runs, so an icon is a handful of rects. */
export function iconRects(name: IconName): Array<[x: number, y: number, w: number]> {
  const rows = ICONS[name];
  const out: Array<[number, number, number]> = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let w = 1;
        while (row[x + w] === "#") w++;
        out.push([x, y, w]);
        x += w;
      } else x++;
    }
  });
  return out;
}
