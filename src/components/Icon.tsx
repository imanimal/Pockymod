export type IconName = keyof typeof BITMAPS;
export const ICON_NAMES = Object.keys(BITMAPS) as IconName[];

/** The bitmap rows for an icon, for tests. */
export function bitmap(name: IconName): readonly string[] {
  return BITMAPS[name];
}

export function Icon({ name, size, big, className, title }: { name: IconName; size?: 9 | 18 | 27 | 36 | 54; big?: boolean; className?: string; title?: string }) {
  const rows = BITMAPS[name];
  const cls = ["i", big ? "big" : "", size ? `s${size}` : "", className ?? ""].filter(Boolean).join(" ");
  return (
    <svg className={cls} viewBox="0 0 9 9" aria-hidden={title ? undefined : true} role={title ? "img" : undefined}>
      {title ? <title>{title}</title> : null}
      {rows.flatMap((row, y) =>
        [...row].map((c, x) => (c === "1" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null)),
      )}
    </svg>
  );
}
